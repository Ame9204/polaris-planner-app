import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    alias(libs.plugins.kotlinJvm)
    alias(libs.plugins.composeMultiplatform)
    alias(libs.plugins.composeCompiler)
}

dependencies {
    implementation(project(":shared"))

    implementation(compose.desktop.currentOs)
    implementation(libs.kotlinx.coroutinesSwing)

    implementation(libs.compose.uiToolingPreview)
}

compose.desktop {
    application {
        mainClass = "dev.ame.polaris.MainKt"

        nativeDistributions {
            targetFormats(TargetFormat.Dmg, TargetFormat.Msi, TargetFormat.Deb)
            packageName = "Polaris"          // the name you see in Start, Settings → Apps, and the install folder
            packageVersion = "1.0.0"         // bump this for every release (MSI needs MAJOR.MINOR.PATCH)
            description = "Your day at a glance: schedule, calendar, tasks and notes"
            vendor = "Ame"

            // The installer bundles a trimmed-down Java with only these parts. Gradle's
            // `suggestRuntimeModules` finds most of them; java.net.http (internet for sync and
            // weather) and jdk.crypto.ec (secure HTTPS connections) are loaded indirectly, so
            // they're added by hand. Missing one = a crash on start.
            modules(
                "java.instrument", "java.management", "java.prefs", "jdk.unsupported",
                "java.net.http", "jdk.crypto.ec", "java.naming",
            )

            windows {
                // App icon (generated by design/icon/make_icons.py)
                iconFile.set(project.file("icons/polaris.ico"))
                // Never change this: it's how Windows knows a new version replaces the old one
                upgradeUuid = "fd305754-76e1-4031-8717-410fc06d7446"
                perUserInstall = true        // installs for you only, no admin prompt
                menu = true                  // Start-menu entry
                menuGroup = "Polaris"
                shortcut = true              // desktop shortcut
                dirChooser = true            // lets you pick where to install
            }
            macOS { iconFile.set(project.file("icons/polaris.icns")) }
            linux { iconFile.set(project.file("icons/polaris.png")) }
        }
    }
}